using System.Text;
using System.Text.Json.Nodes;
using System.Xml.Linq;
using FlowtideDotNet.Substrait.Documentation.Catalog;

namespace FlowtideDotNet.Substrait.Documentation;

internal static class ReferenceGenerator
{
    private sealed record Category(string Key, string Title, string ClassName);
    private static readonly Category[] Categories =
    [
        new("scalar", "Scalar functions and operators", "Scalar"), new("aggregate", "Aggregate functions", "Aggregate"),
        new("window", "Window functions", "Window"), new("table", "Table functions", "Table")
    ];
    private static readonly HashSet<string> SeparateMetadata =
    ["notes", "sql_signature", "sql_example", "sql_examples", "doc_url", "legacy_extension_uri", "definition_kind"];
    private const string Guidance = "Names and examples use Flowtide SQL. Square brackets in signatures mark optional arguments; "
        + "they are not literal SQL. Extension signatures, type declarations and required options describe Substrait bindings, "
        + "not additional SQL arguments. The Flowtide notes and constraints apply to each listed profile. "
        + "Aggregate, window and table functions are separate capabilities.";

    public static IReadOnlyDictionary<string, string> Generate(DialectCatalog catalog, string introduction)
    {
        var markdown = new StringBuilder("<!-- Generated by FlowtideDotNet.Substrait.DocGenerator. Edit substrait/dialect.yaml, substrait/extensions/ or docs/reference/expressions.md, then regenerate. -->\n\n");
        markdown.Append(introduction.Replace("\r\n", "\n").Trim()).Append("\n\n## Function reference\n\n").Append(Guidance).Append('\n');
        var xml = new XElement("documentation", new XComment(" Generated from the Substrait catalog. Do not edit; run FlowtideDotNet.Substrait.DocGenerator. "));
        var index = new XElement("topic", new XAttribute("id", "functions"), new XElement("para", Guidance));
        var links = new XElement("list", new XAttribute("type", "bullet"));
        index.Add(links);
        xml.Add(index);
        var functions = catalog.Functions().Where(entry => entry.Data["metadata"]?["sql_exposed"]?.GetValue<bool>() != false).ToArray();
        foreach (var category in Categories)
        {
            var groups = functions.Where(entry => entry.Category == category.Key)
                .GroupBy(SqlSignature).OrderBy(group => group.Key, StringComparer.Ordinal).ToArray();
            markdown.Append("\n## ").Append(category.Title).Append('\n');
            links.Add(new XElement("item", new XElement("description",
                new XElement("see", new XAttribute("cref", $"FlowtideDotNet.Substrait.Sql.SqlFunctionReference.{category.ClassName}")),
                ": " + string.Join("; ", groups.Select(group =>
                {
                    var aliases = group.SelectMany(entry => (entry.Data["metadata"]?["sql_aliases"]).Strings()).Distinct(StringComparer.Ordinal).ToArray();
                    return group.Key + (aliases.Length == 0 ? "" : " (aliases: " + string.Join(", ", aliases) + ")");
                })))));
            var topic = new XElement("topic", new XAttribute("id", "functions-" + category.Key), new XElement("para", Guidance));
            xml.Add(topic);
            foreach (var group in groups)
            {
                markdown.Append("\n### ").Append(Code(group.Key)).Append('\n');
                topic.Add(new XElement("para", new XElement("b", group.Key)));
                foreach (var entry in group)
                {
                    var implementations = catalog.Implementations(entry).ToArray();
                    if (implementations.Length == 0) throw new InvalidDataException($"{catalog.Dialect.Path}#{entry.Pointer}: No implementation matches the supported profile.");
                    var facts = Facts(entry, implementations).ToArray();
                    if (group.Count() > 1)
                    {
                        var profile = "Profile: " + string.Join(", ", entry.Data["supported_impls"].Strings().Select(signature => signature.Length == 0 ? "no arguments" : signature));
                        markdown.Append("\n**").Append(profile).Append("**\n");
                        topic.Add(new XElement("para", new XElement("b", profile)));
                    }
                    var notes = entry.Data["metadata"]?["notes"].Text()
                        ?? (entry.Category == "table" ? implementations[0].Definition["description"].Text() : null);
                    if (notes != null)
                    {
                        markdown.Append('\n').Append(notes).Append('\n');
                        topic.Add(new XElement("para", notes));
                    }
                    var list = new XElement("list", new XAttribute("type", "bullet"));
                    topic.Add(list);
                    markdown.Append('\n');
                    foreach (var (label, value) in facts)
                    {
                        // Facts are paragraphs, not table cells, so SQL pipes and nested type syntax remain intact.
                        markdown.Append("- **").Append(label).Append(":** ").Append(Code(value)).Append('\n');
                        list.Add(new XElement("item", new XElement("description", label + ": ", new XElement("c", value))));
                    }
                    foreach (var example in Examples(entry))
                    {
                        markdown.Append("\n").Append(Fenced(example, "sql")).Append('\n');
                        topic.Add(new XElement("code", new XAttribute("language", "sql"), example));
                    }
                    if (entry.Data["metadata"]?["doc_url"].Text() is { } url)
                    {
                        markdown.Append("\n[Detailed documentation](").Append(url).Append(")\n");
                        topic.Add(new XElement("para", new XElement("see", new XAttribute("href", url), "Detailed documentation")));
                    }
                }
            }
        }
        return new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["docs/docs/expressions/functions-reference.md"] = markdown.ToString(),
            ["docs/llms/expressions.txt"] = markdown.ToString(),
            ["docs/reference/sql-functions.xml"] = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" + xml.ToString() + "\n"
        };
    }

    private static string SqlSignature(FunctionEntry entry) => entry.Data["metadata"]?["sql_signature"].Text()
        ?? throw new InvalidDataException($"Missing sql_signature at {entry.Pointer}.");

    private static IEnumerable<(string Label, string Value)> Facts(FunctionEntry entry, ResolvedImplementation[] implementations)
    {
        yield return ("Extension signatures", string.Join(", ", entry.Data["supported_impls"].Strings().Select(signature => entry.Data["name"].Text() + ":" + signature)));
        yield return ("Extension source", implementations[0].Source.Urn);
        foreach (var contract in implementations.Select(Contract).Distinct(StringComparer.Ordinal)) yield return ("Extension type declaration", contract);
        if (entry.Data["required_options"] is JsonObject options)
            foreach (var option in options.OrderBy(pair => pair.Key, StringComparer.Ordinal)) yield return ("Required Substrait option " + option.Key, Format(option.Value));
        if (entry.Data["variadic"] is JsonObject variadic) yield return ("Variadic arguments", Format(variadic));
        if (entry.Data["metadata"] is JsonObject metadata)
            foreach (var fact in metadata.Where(pair => !SeparateMetadata.Contains(pair.Key)).OrderBy(pair => pair.Key, StringComparer.Ordinal))
                yield return (Label(fact.Key), Format(fact.Value));
        // Table output shape and literal arguments belong to the source definition's custom metadata.
        if (entry.Category == "table")
            foreach (var definition in implementations.Select(impl => impl.Definition).Distinct())
            {
                if (definition["metadata"] is JsonObject details)
                    foreach (var fact in details.Where(pair => pair.Key != "legacy_extension_uri").OrderBy(pair => pair.Key, StringComparer.Ordinal))
                        yield return (Label(fact.Key), Format(fact.Value));
            }
    }

    private static string Contract(ResolvedImplementation implementation)
    {
        var impl = implementation.Data;
        var args = impl["args"].Objects().Select(arg => arg.ContainsKey("options") ? "enum(" + string.Join(", ", arg["options"].Strings()) + ")"
            : Format(arg["value"] ?? arg["type"]) + (arg["constant"]?.GetValue<bool>() == true ? " (constant)" : ""));
        var result = "(" + string.Join(", ", args) + ") -> ";
        result += impl["output_columns"] is JsonArray columns
            ? "rows(" + string.Join(", ", columns.Objects().Select(column => column["name"].Text() + ": " + Format(column["value"]))) + ")"
            : Format(impl["return"]);
        if (impl["nullability"].Text() is { } nullability) result += "; nullability=" + nullability;
        return result;
    }

    private static IEnumerable<string> Examples(FunctionEntry entry)
    {
        if (entry.Data["metadata"]?["sql_example"].Text() is { } example) yield return example;
        foreach (var value in (entry.Data["metadata"]?["sql_examples"]).Strings()) yield return value;
    }

    private static string Format(JsonNode? node) => node switch
    {
        null => "null",
        JsonObject map => string.Join("; ", map.OrderBy(pair => pair.Key, StringComparer.Ordinal).Select(pair => pair.Key + "=" + Format(pair.Value))),
        JsonArray array => "[" + string.Join(", ", array.Select(Format)) + "]",
        _ => node.Text() ?? node.ToJsonString()
    };

    private static string Label(string key) => char.ToUpperInvariant(key[0]) + key[1..].Replace('_', ' ');
    private static string Code(string text)
    {
        // CommonMark code spans can contain backticks by using a longer delimiter.
        var delimiter = Delimiter(text, '`');
        return delimiter + " " + text.Replace("\r\n", " ").Replace('\n', ' ') + " " + delimiter;
    }
    private static string Fenced(string text, string language) => Delimiter(text, '`', 3) + language + "\n" + text + "\n" + Delimiter(text, '`', 3);
    private static string Delimiter(string text, char character, int minimum = 1)
    {
        var longest = text.Split(character).Length == 1 ? 0 : System.Text.RegularExpressions.Regex.Matches(text, $"{character}+").Max(match => match.Length);
        return new string(character, Math.Max(minimum, longest + 1));
    }
}
